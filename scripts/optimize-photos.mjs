import sharp from 'sharp'
import { readdir, stat, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

// Re-encodes the photographs that get shipped to the browser.
//
// Same arrangement as optimize-screenshots.mjs: `originals/` is the source of
// truth and is never imported; the served copies are written one directory up.
// Unlike the screenshots, a photo fills the whole screen, so each is written at
// several widths for the <img srcset> to choose from, plus a tiny inline copy
// (photo-lqip.ts) that paints in the same instant as the page.
//
// Phone photos carry EXIF — camera, time and often GPS. sharp drops all
// metadata on output unless asked to keep it, and .rotate() applies the EXIF
// orientation first so the picture stays upright once that tag is gone.

const dir = new URL('../app/assets/photos/', import.meta.url).pathname
const srcDir = path.join(dir, 'originals')

const WIDTHS = [640, 1080, 1600]
const QUALITY = 62
const LQIP_WIDTH = 24

await mkdir(srcDir, { recursive: true })

const files = (await readdir(srcDir)).filter(f => /\.(jpe?g|png|webp)$/i.test(f))
if (files.length === 0) {
  console.error(`No source photos in ${srcDir}`)
  process.exit(1)
}

const lqip = {}
for (const f of files) {
  const src = path.join(srcDir, f)
  const name = f.replace(/\.[^.]+$/, '')
  for (const w of WIDTHS) {
    const out = path.join(dir, `${name}-${w}.webp`)
    await sharp(src).rotate().resize(w, null, { withoutEnlargement: true }).webp({ quality: QUALITY, effort: 6 }).toFile(out)
    console.log(`${name}-${w}.webp  ${((await stat(out)).size / 1024).toFixed(0)}K`)
  }
  const tiny = await sharp(src).rotate().resize(LQIP_WIDTH).webp({ quality: 40 }).toBuffer()
  lqip[name] = `data:image/webp;base64,${tiny.toString('base64')}`
}

const body = Object.entries(lqip).map(([k, v]) => `  '${k}': '${v}',`).join('\n')
await writeFile(
  path.join(dir, '../photo-lqip.ts'),
  `// GENERATED by scripts/optimize-photos.mjs — do not edit by hand.\n\nexport const PHOTO_LQIP: Record<string, string> = {\n${body}\n}\n`,
)
